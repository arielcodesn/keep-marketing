def main():
    lines = ["# Base clips", "",
             "Every clip has a `frames/<clip>/` folder with a frame every 0.5 s (`00.0s.jpg`, `00.5s.jpg`, …), "
             "a `contact_sheet.jpg` of all frames, and a `timeline.md` describing each half-second.", "",
             "| Clip | Background | Framing | Beat | Use for |", "|---|---|---|---|---|"]
    for name, c in CLIPS.items():
        d = os.path.join(ROOT, "frames", name)
        rows = [f"| {t}s | `{t.zfill(4)}s.jpg` | {desc} |" for t, desc in c["rows"]]
        md = [f"# {name}", "", c["summary"], "",
              f"- **Background:** {c['background']}",
              f"- **Framing:** {c['framing']}",
              f"- **Branding:** {c['branding']}",
              f"- **Cutout:** {c['cutout']}",
              f"- **Beat:** {c['beat']}",
              f"- **Good for:** {c['use']}",
              f"- **Audio:** {c['audio']}", "",
              "![contact sheet](contact_sheet.jpg)", "",
              "| Time | Frame | What happens |", "|---|---|---|", *rows, ""]
        open(os.path.join(d, "timeline.md"), "w").write("\n".join(md))
        lines.append(f"| [{name}](frames/{name}/timeline.md) | {c['background'].split('.')[0]} | {c['framing'].split('.')[0]} | {c['beat']} | {c['use']} |")
    open(os.path.join(ROOT, "README.md"), "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
